/**
 * Which commit a build is "of". Pure, so vite.config.ts and the test agree.
 *
 * Every PostHog event and every playback report carries `build_sha`, and from
 * the 2026-11-03 publish until this landed every one of them read "unknown":
 * Lovable's publish build has neither a git binary nor a `.git` directory, so
 * nothing at build time could name the commit. A failure nobody can attribute
 * to a build cannot be measured, so the sha now travels IN the tree:
 * `.github/workflows/stamp-build-sha.yml` writes `src/buildInfo.ts` on every
 * push to main and commits it back ("chore: stamp build <sha>").
 *
 * That stamp commit is a second commit on top of the code it describes, so
 * the rules below make every production build of the same code report the
 * same sha — the CODE commit, never the stamp:
 *
 *   1. VITE_BUILD_SHA, when set, wins. An operator can always say.
 *   2. With git available and HEAD being a stamp commit, the stamped sha
 *      (HEAD's parent) — so CI and the iOS workflow, which build the stamp
 *      commit, agree with Lovable, which builds without git and reads the
 *      file.
 *   3. Otherwise git HEAD: a developer's own commit, a branch, main before
 *      the stamp has landed.
 *   4. Otherwise the stamped file.
 *   5. Otherwise "unknown".
 */
export const STAMP_SUBJECT_PREFIX = "chore: stamp build";

const SHA_RE = /^[0-9a-f]{40}$/;

/**
 * @param {object} input
 * @param {string | undefined} input.env       VITE_BUILD_SHA
 * @param {string} input.gitHead               `git rev-parse HEAD`, or "" when git is unavailable
 * @param {string} input.gitHeadSubject        `git log -1 --format=%s`, or ""
 * @param {string} input.gitParent             `git rev-parse HEAD^`, or ""
 * @param {string} input.stamped               the sha in src/buildInfo.ts, or ""
 */
export function resolveBuildSha({ env, gitHead, gitHeadSubject, gitParent, stamped }) {
  if (env && SHA_RE.test(env)) return env;
  const headIsStamp =
    SHA_RE.test(gitHead) &&
    gitHeadSubject.startsWith(STAMP_SUBJECT_PREFIX) &&
    SHA_RE.test(stamped) &&
    stamped === gitParent;
  if (headIsStamp) return stamped;
  if (SHA_RE.test(gitHead)) return gitHead;
  if (SHA_RE.test(stamped)) return stamped;
  return "unknown";
}

/** The file the workflow writes. One line of data, so a diff of it is readable. */
export function renderBuildInfo(sha, stampedAt) {
  return `// GENERATED by .github/workflows/stamp-build-sha.yml on every push to main.
// Do not edit by hand. See scripts/build-sha/resolve.mjs for how it is read.
export const BUILD_INFO = { sha: "${sha}", stampedAt: "${stampedAt}" } as const;
`;
}

/** Read the sha back out of the file's text; "" when it carries none. */
export function parseBuildInfo(text) {
  const m = /sha:\s*"([0-9a-f]{40})"/.exec(text || "");
  return m ? m[1] : "";
}
